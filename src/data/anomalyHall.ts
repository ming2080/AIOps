export const ALERT_LEVELS: AlertLevel[] = ['重大告警', '高级告警', '中级告警', '一般告警'];

/** 按告警级别筛选，'全部' 返回全部记录 */
export function filterAlertsByLevel(alerts: AnomalyAlert[], level: AlertLevel | '全部'): AnomalyAlert[] {
  if (level === '全部') return alerts;
  return alerts.filter((a) => a.level === level);
}

/** 统计各告警级别的条数 */
export function countAlertsByLevel(alerts: AnomalyAlert[]): Record<AlertLevel, number> {
  const counts: Record<AlertLevel, number> = { '重大告警': 0, '高级告警': 0, '中级告警': 0, '一般告警': 0 };
  alerts.forEach((a) => {
    counts[a.level] += 1;
  });
  return counts;
}

/** 趋势区间内的告警总数 */
export function sumTrendAlerts(days: AnomalyTrendDay[]): number {
  return days.reduce((sum, d) => sum + d.alert, 0);
}
